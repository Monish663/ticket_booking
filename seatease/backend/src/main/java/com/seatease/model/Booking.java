package com.seatease.model;

import java.time.LocalDateTime;
import java.util.List;

/**
 * Booking — Represents a seat booking made by a customer.
 *
 * OOP Concepts demonstrated:
 * - Composition: A Booking "has-a" Customer and a list of Seats.
 * - Encapsulation: All fields are private.
 *
 * A Booking links a Customer to one or more Seats. The total amount
 * is computed by the backend (never trusted from the frontend).
 */
public class Booking {

    private int bookingId;              // Auto-generated by MySQL
    private Customer customer;          // Composition: Booking has-a Customer
    private List<Seat> selectedSeats;   // Composition: Booking has-a list of Seats
    private double totalAmount;         // Calculated server-side
    private LocalDateTime bookingDate;  // Timestamp of booking creation
    private String bookingStatus;       // CONFIRMED or CANCELLED

    // Default constructor
    public Booking() {
    }

    // Full constructor
    public Booking(int bookingId, Customer customer, List<Seat> selectedSeats,
                   double totalAmount, LocalDateTime bookingDate, String bookingStatus) {
        this.bookingId = bookingId;
        this.customer = customer;
        this.selectedSeats = selectedSeats;
        this.totalAmount = totalAmount;
        this.bookingDate = bookingDate;
        this.bookingStatus = bookingStatus;
    }

    // --- Getters and Setters ---

    public int getBookingId() {
        return bookingId;
    }

    public void setBookingId(int bookingId) {
        this.bookingId = bookingId;
    }

    public Customer getCustomer() {
        return customer;
    }

    public void setCustomer(Customer customer) {
        this.customer = customer;
    }

    public List<Seat> getSelectedSeats() {
        return selectedSeats;
    }

    public void setSelectedSeats(List<Seat> selectedSeats) {
        this.selectedSeats = selectedSeats;
    }

    public double getTotalAmount() {
        return totalAmount;
    }

    public void setTotalAmount(double totalAmount) {
        this.totalAmount = totalAmount;
    }

    public LocalDateTime getBookingDate() {
        return bookingDate;
    }

    public void setBookingDate(LocalDateTime bookingDate) {
        this.bookingDate = bookingDate;
    }

    public String getBookingStatus() {
        return bookingStatus;
    }

    public void setBookingStatus(String bookingStatus) {
        this.bookingStatus = bookingStatus;
    }

    @Override
    public String toString() {
        return "Booking{" +
                "bookingId=" + bookingId +
                ", customer=" + customer +
                ", selectedSeats=" + selectedSeats +
                ", totalAmount=" + totalAmount +
                ", bookingDate=" + bookingDate +
                ", bookingStatus='" + bookingStatus + '\'' +
                '}';
    }
}
